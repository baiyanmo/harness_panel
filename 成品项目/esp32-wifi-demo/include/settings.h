// ============================================================
#define AP_SSID     "pxfish"        // 热点名称（手机搜这个）
#define AP_PASSWORD nullptr          // 热点密码（nullptr = 开放）

// ============================================================
// 路由器连接超时（毫秒）
// 超过此时间连不上就自动开热点
// ============================================================
#define WIFI_CONNECT_TIMEOUT_MS  15000

// ============================================================
// mDNS 主机名（STA 模式下可通过 http://esp32-wifi.local 访问）
// ============================================================
#define HOSTNAME "esp32-wifi"

// ============================================================
// 巴法云 MQTT
// ============================================================
#define BEMFA_MQTT_SERVER  "mqtt.bemfa.com"
#define BEMFA_MQTT_PORT    9501
#define BEMFA_MQTT_KEEPALIVE 30  // 心跳间隔（秒）

// ============================================================
// 设备信息（对应巴法云 topic）
// ============================================================
#define DEVICE_TYPE  "002"         // 设备类型，001插座 002灯 003风扇 005空调 006开关 009窗帘
#define DEVICE_NAME  "台灯"         // 设备昵称
#define BEMFA_TOPIC  "LIGHT002"   // 巴法云控制台创建的设备主题

// ============================================================
// 串口（连接 STM32）
//
// GPIO16/17 是 PSRAM 引脚，大部分 ESP32 模块不能用作串口！
// 改用 GPIO32(RX)、GPIO33(TX)
//
// 接线：ESP32 GPIO32 → STM32 TX
//        ESP32 GPIO33 → STM32 RX
//        ESP32 GND    ↔ STM32 GND
//
// 如果暂时不接 STM32，把 ENABLE_SERIAL_BRIDGE 改为 0
// ============================================================
#define ENABLE_SERIAL_BRIDGE 1   // 1 = 启用串口桥接，0 = 禁用（没接 STM32 时务必关掉）
#define STM32_BAUD   9600       // 串口波特率
#define STM32_RX_PIN 32           // ESP32 RX2（接 STM32 TX），避免用 16(PSRAM)
#define STM32_TX_PIN 33           // ESP32 TX2（接 STM32 RX），避免用 17(PSRAM)
